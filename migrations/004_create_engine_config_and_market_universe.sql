CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS market_signal_engine;

ALTER TABLE market_signal_engine.signals
  ADD COLUMN IF NOT EXISTS strategy_version TEXT NOT NULL DEFAULT 'legacy';

ALTER TABLE market_signal_engine.opportunities
  ADD COLUMN IF NOT EXISTS strategy_version TEXT NOT NULL DEFAULT 'legacy';

CREATE TABLE IF NOT EXISTS market_signal_engine.engine_config (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  key VARCHAR UNIQUE NOT NULL,
  value TEXT NOT NULL,
  value_type VARCHAR NOT NULL,
  category VARCHAR NOT NULL,
  description TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT engine_config_value_type_check CHECK (value_type IN ('string', 'number', 'boolean', 'json'))
);

CREATE TABLE IF NOT EXISTS market_signal_engine.market_symbols (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  symbol VARCHAR UNIQUE NOT NULL,
  provider_symbol VARCHAR,
  display_name VARCHAR,
  asset_type VARCHAR NOT NULL,
  sector VARCHAR,
  industry VARCHAR,
  exchange VARCHAR,
  market VARCHAR,
  timezone VARCHAR NOT NULL,
  session_type VARCHAR NOT NULL,
  supports_intraday BOOLEAN NOT NULL DEFAULT true,
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT market_symbols_asset_type_check CHECK (asset_type IN ('STOCK', 'ETF', 'CRYPTO', 'INDEX', 'FOREX', 'COMMODITY', 'REIT', 'FUTURE')),
  CONSTRAINT market_symbols_session_type_check CHECK (session_type IN ('US_REGULAR', 'TWENTY_FOUR_SEVEN'))
);

CREATE TABLE IF NOT EXISTS market_signal_engine.symbol_timeframes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  symbol_id UUID NOT NULL REFERENCES market_signal_engine.market_symbols(id) ON DELETE CASCADE,
  timeframe VARCHAR NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (symbol_id, timeframe),
  CONSTRAINT symbol_timeframes_timeframe_check CHECK (timeframe IN ('1m', '5m', '15m', '1d', '1w'))
);

CREATE INDEX IF NOT EXISTS idx_engine_config_active_category
  ON market_signal_engine.engine_config (is_active, category);

CREATE INDEX IF NOT EXISTS idx_market_symbols_active_asset_type
  ON market_signal_engine.market_symbols (is_active, asset_type);

CREATE INDEX IF NOT EXISTS idx_market_symbols_sector
  ON market_signal_engine.market_symbols (sector);

CREATE INDEX IF NOT EXISTS idx_market_symbols_industry
  ON market_signal_engine.market_symbols (industry);

CREATE INDEX IF NOT EXISTS idx_symbol_timeframes_symbol_active
  ON market_signal_engine.symbol_timeframes (symbol_id, is_active);

CREATE INDEX IF NOT EXISTS idx_signals_strategy_version
  ON market_signal_engine.signals (strategy_version);

CREATE INDEX IF NOT EXISTS idx_opportunities_strategy_version
  ON market_signal_engine.opportunities (strategy_version);

